#!/usr/bin/env python3
"""Generate the layout bench fixtures (layout §16.4; roadmap M4.0). Deterministic: rerunning
writes identical bytes, and a test checks the committed files parse and type-check clean.

  fixtures/bench/dense-7x40.idef0    7 boxes, 40 arrows: every §6.2 template class
  fixtures/bench/arrange-worst-7.idef0  7 boxes, all-to-all control arcs, one 9-arrow side

Ranks are left out, so the parser assigns them in declaration order (metamodel §16.3).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAMES = ["Plan Orders", "Check Credit", "Pick Goods", "Pack Shipment", "Ship Goods", "Bill Customer", "Close Orders"]


def header(name, abbrev, purpose):
    return (f'idef0 0.2\n# Generated by scripts/gen-bench-fixtures.py; do not edit.\n'
            f'model "{name}" {{\n  abbrev "{abbrev}"\n  purpose "{purpose}"\n  viewpoint "Layout benchmark"\n}}\n\n')


def concepts(n):
    return "".join(f'concept d{k} "Data {k}" {{ description "Benchmark data item {k}." }}\n' for k in range(1, n + 1)) + "\n"


def context(title):
    return (f'diagram A-0 "{title}" {{\n  box 0 "{title}" key=top\n'
            '  arrow @d1 : I1 -> 0I1\n  arrow @d2 : C1 -> 0C1\n  arrow @d3 : 0O1 -> O1\n  arrow @d4 : M1 -> 0M1\n}\n\n')


def boxes():
    return "".join(f'  box {i} "{name}"\n' for i, name in enumerate(NAMES, 1))


def dense():
    arrows = []
    # boundary arrows, matching sides (straight) and role shifts (dog-legs)
    arrows += ["I1 -> 1I", "I2 -> 1I", "I3 -> 2I", "C1 -> 1C", "C2 -> 3C", "C3 -> 4C", "M1 -> 3M", "M2 -> 5M"]
    arrows += ["C4 -> 2I", "I4 -> 6C"]
    # forward input chain, forward controls (skip one), forward mechanisms
    arrows += [f"{i}O -> {i + 1}I" for i in range(1, 7)]
    arrows += [f"{i}O -> {i + 2}C" for i in range(1, 6)]
    arrows += ["1O -> 4M", "2O -> 6M", "3O -> 7M"]
    # feedback: control up and over, input and mechanism down and under
    arrows += ["4O -> 2C", "5O -> 1C", "6O -> 3C", "7O -> 5C", "7O -> 2C", "5O -> 3C"]
    arrows += ["6O -> 2I", "7O -> 4I", "5O -> 1I"]
    arrows += ["6O -> 1M", "7O -> 3M", "4O -> 2M"]
    # self loops, outputs
    arrows += ["2O -> 2C", "4O -> 4I"]
    arrows += ["6O -> O1", "7O -> O2"]
    assert len(arrows) == 40, len(arrows)
    body = "".join(f"  arrow @d{(k % 40) + 1} : {a}\n" for k, a in enumerate(arrows))
    return header("Dense Bench", "DNS", "Layout benchmark: 7 boxes, 40 arrows.") + concepts(40) + \
        context("Fulfill Orders") + f"diagram A0 {{\n{boxes()}\n{body}}}\n"


def worst():
    # all-to-all control arcs in a scrambled box order, plus a 9-arrow input side on box 4
    order = [4, 7, 1, 6, 2, 5, 3]
    arrows = [f"{i}O -> {j}C" for i in order for j in order if i != j]
    arrows += [f"I{k} -> 4I" for k in range(1, 10)]
    arrows += ["7O -> O1"]
    body = "".join(f"  arrow @d{(k % 40) + 1} : {a}\n" for k, a in enumerate(arrows))
    return header("Arrange Worst Case", "AWC", "Auto-Arrange worst case: all-to-all controls, a 9-arrow side.") + \
        concepts(40) + context("Fulfill Orders") + f"diagram A0 {{\n{boxes()}\n{body}}}\n"


for name, text in [("dense-7x40", dense()), ("arrange-worst-7", worst())]:
    with open(os.path.join(ROOT, "fixtures", "bench", f"{name}.idef0"), "w", newline="\n") as f:
        f.write(text)
